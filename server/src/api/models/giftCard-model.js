'use strict';

//bcrypt for passwords
import bcrypt from "bcrypt";
import promisePool from "../../utils/database.js";

//default datastructure
const default_giftCard = {
    id : 0,     //auto generated by backend
    value: 15.5,
    expiration_date : "2026-01-01",
    password: "giftcardpassword",
    message : "defauld giftcard, password is used to validate the giftcard",
    order: 0,   // foreign key to order.id
    user : 0,   // foreign key to user.id
}



